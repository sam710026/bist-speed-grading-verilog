// BISTed unsigned adder using a 4-stage LFSR APG and a MISR signature analyzer.
// Supported top modules:
//   - bist_adder6  : unsigned 6-bit adder,  7-bit MISR signature
//   - bist_adder12 : unsigned 12-bit adder, 13-bit MISR signature
// -----------------------------------------------------------------------------
`timescale 1ns/1ps

module bist_adder6 (
    input  wire       clk,
    input  wire       reset,
    output wire [3:0] lfsr_state,
    output wire [5:0] a,
    output wire [5:0] b,
    output wire [6:0] sum,
    output wire [6:0] signature,
    output wire [4:0] pattern_count,
    output wire       done
);
    bist_adder #(.N(6)) u_bist_adder (
        .clk(clk),
        .reset(reset),
        .lfsr_state(lfsr_state),
        .a(a),
        .b(b),
        .sum(sum),
        .signature(signature),
        .pattern_count(pattern_count),
        .done(done)
    );
endmodule

