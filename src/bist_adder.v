// Generic BIST top. N should be 6 or 12 for this assignment.
module bist_adder #(
    parameter N = 6
)(
    input  wire         clk,
    input  wire         reset,
    output reg  [3:0]   lfsr_state,
    output wire [N-1:0] a,
    output wire [N-1:0] b,
    output wire [N:0]   sum,
    output reg  [N:0]   signature,
    output reg  [4:0]   pattern_count,
    output reg          done
);
    localparam SUM_W = N + 1;

    // 4-stage LFSR with primitive polynomial x^4 + x + 1.
    // Starting from 0001, this generates 15 nonzero states.
    wire lfsr_feedback;
    wire [3:0] lfsr_next;
    assign lfsr_feedback = lfsr_state[3] ^ lfsr_state[0];
    assign lfsr_next     = {lfsr_state[2:0], lfsr_feedback};

    // Expand the 4-bit LFSR state into two adder operands.
    // This keeps exactly 15 BIST patterns while still driving all adder inputs.
    generate
        if (N == 6) begin : GEN_PATTERN_6
            assign a = {lfsr_state, lfsr_state[3:2]};
            assign b = {lfsr_state[1:0], lfsr_state};
        end else begin : GEN_PATTERN_12
            assign a = {lfsr_state,
                        (lfsr_state ^ 4'b1011),
                        {lfsr_state[1:0], lfsr_state[3:2]}};
            assign b = {{lfsr_state[0], lfsr_state[3:1]},
                        lfsr_state,
                        ~lfsr_state};
        end
    endgenerate

    // Unsigned ripple-carry adder, expressed as generate logic equations.
    ripple_adder #(.N(N)) u_adder (
        .a(a),
        .b(b),
        .sum(sum)
    );

    // MISR masks. The LSB is the constant term of the polynomial.
    // For 6-bit adder:  W=7,  p(x)=x^7+x+1.
    // For 12-bit adder: W=13, p(x)=x^13+x^4+x^3+x+1.
    wire [SUM_W-1:0] tap_mask;
    assign tap_mask = (N == 6) ? 7'b0000011 : 13'b0000000011011;

    wire feedback_misr;
    wire [SUM_W-1:0] sig_shifted;
    wire [SUM_W-1:0] sig_next;
    assign feedback_misr = signature[SUM_W-1];
    assign sig_shifted   = {signature[SUM_W-2:0], 1'b0};
    assign sig_next      = sig_shifted ^ (feedback_misr ? tap_mask : {SUM_W{1'b0}}) ^ sum;

    always @(posedge clk or posedge reset) begin
        if (reset) begin
            lfsr_state    <= 4'b0001;
            pattern_count <= 5'd0;
            signature     <= {SUM_W{1'b0}};
            done          <= 1'b0;
        end else if (!done) begin
            // Compact the CUT response generated by the current LFSR state.
            signature <= sig_next;

            // Move to the next pseudo-random pattern.
            lfsr_state <= lfsr_next;

            if (pattern_count == 5'd14) begin
                pattern_count <= 5'd15;
                done          <= 1'b1;
            end else begin
                pattern_count <= pattern_count + 5'd1;
                done          <= 1'b0;
            end
        end
    end
endmodule

module ripple_adder #(
    parameter N = 6
)(
    input  wire [N-1:0] a,
    input  wire [N-1:0] b,
    output wire [N:0]   sum
);
    wire [N:0] carry;
    wire [N-1:0] p;
    wire [N-1:0] g;

    assign carry[0] = 1'b0;
    assign p = a ^ b;
    assign g = a & b;

    genvar i;
    generate
        for (i = 0; i < N; i = i + 1) begin : GEN_FULL_ADDER
            assign sum[i] = p[i] ^ carry[i];
            assign carry[i+1] = g[i] | (p[i] & carry[i]);
        end
    endgenerate

    assign sum[N] = carry[N];
endmodule
